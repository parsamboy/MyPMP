def rpr_of(r, create=True):
    rpr = r.find(q('rPr'))
    if rpr is None and create:
        rpr = etree.Element(q('rPr'))
        r.insert(0, rpr)
    return rpr


def set_color(rpr, hexcol):
    c = rpr.find(q('color'))
    if c is None:
        c = etree.SubElement(rpr, q('color'))
    c.set(q('val'), hexcol)


def paint_red_strike(p):
    n = 0
    for r in p.iter(q('r')):
        rpr = rpr_of(r, create=True)
        set_color(rpr, RED)
        if rpr.find(q('strike')) is None:
            etree.SubElement(rpr, q('strike'))
        n += 1
    return n


def green_para_like(template, text):
    p = etree.Element(q('p'))
    ppr = template.find(q('pPr'))
    if ppr is not None:
        nppr = copy.deepcopy(ppr)
        # don't copy sectPr
        sp = nppr.find(q('sectPr'))
        if sp is not None:
            nppr.remove(sp)
        p.append(nppr)
    r = etree.SubElement(p, q('r'))
    rpr = etree.SubElement(r, q('rPr'))
    fonts(rpr, TNR, LOTUS)
    set_color(rpr, GREEN)
    te = etree.SubElement(r, q('t'))
    te.set(XML_SPACE, 'preserve')
    te.text = text
    return p


def freeze_xml(el):
    return etree.tostring(el)


def build():
    zin = zipfile.ZipFile(SRC)
    parts = {n: zin.read(n) for n in zin.namelist()}
    zin.close()
    doc = etree.fromstring(parts['word/document.xml'])
    body = doc[0]
    kids = list(body)

    def idx_start(s):
        for i, el in enumerate(kids):
            if el.tag == q('p') and ptext(el).strip() == s:
                return i
        return None

    i_toc = idx_start('فهرست مطالب')
    i_pnu = None
    for i, el in enumerate(kids):
        if el.tag == q('p') and 'Payame Noor University' in ptext(el):
            i_pnu = i
            break
    front = [freeze_xml(el) for el in kids[:i_toc]]
    last = [freeze_xml(el) for el in kids[i_pnu:]]

    # collect targets first (objects), apply from end
    red_paras = []
    repl = []  # (p, newtext)
    for el in kids:
        if el.tag != q('p'):
            continue
        t = ptext(el).strip()
        if not t:
            continue
        st = style_of(el) or ''
        if st.startswith('Heading') or st.startswith('TOC') or st == 'Caption':
            continue
        hit_rep = None
        for old, new in REPLACEMENTS:
            if t.startswith(old):
                hit_rep = new
                break
        if hit_rep is not None:
            repl.append((el, hit_rep))
            continue
        for px in RED_PREFIXES:
            if t.startswith(px):
                red_paras.append(el)
                break

    n_red = 0
    for p in red_paras:
        paint_red_strike(p)
        n_red += 1
    n_rep = 0
    # insert from end so next insertions stay valid
    for p, new in reversed(repl):
        paint_red_strike(p)
        gp = green_para_like(p, new)
        p.addnext(gp)
        n_rep += 1

    print('red-only', n_red, 'replaced', n_rep)

    kids2 = list(body)
    i_toc2 = None
    i_pnu2 = None
    for i, el in enumerate(kids2):
        if el.tag != q('p'):
            continue
        tt = ptext(el).strip()
        if tt == 'فهرست مطالب':
            i_toc2 = i
        if 'Payame Noor University' in tt:
            i_pnu2 = i
    front2 = [freeze_xml(el) for el in kids2[:i_toc2]]
    last2 = [freeze_xml(el) for el in kids2[i_pnu2:]]
    if front2 != front:
        raise SystemExit('front changed')
    if last2 != last:
        raise SystemExit('last changed')
    print('freeze OK')

    parts['word/document.xml'] = etree.tostring(
        doc, xml_declaration=True, encoding='UTF-8', standalone=True)
    with zipfile.ZipFile(DST, 'w', zipfile.ZIP_DEFLATED) as zout:
        for k, v in parts.items():
            zout.writestr(k, v)
    print('نوشته شد:', DST, os.path.getsize(DST))


if __name__ == '__main__':
    build()
