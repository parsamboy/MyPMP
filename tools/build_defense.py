LATIN = re.compile(r"[A-Za-z\u00C0-\u024F]")


def script_of(ch: str) -> str:
    o = ord(ch)
    if any(lo <= o <= hi for lo, hi in ARABIC):
        return "fa"
    if LATIN.match(ch):
        return "en"
    return "neutral"


def chunks(s: str):
    """Split text into maximal single-script runs so each keeps its own
    direction, language tag and digit set."""
    out, buf, cur = [], "", "neutral"
    for ch in s:
        sc = script_of(ch)
        if sc == "neutral":
            buf += ch
            continue
        if cur == "neutral":
            cur, buf = sc, buf + ch
        elif sc == cur:
            buf += ch
        else:
            out.append((cur, buf))
            buf, cur = ch, sc
    if buf:
        out.append((cur, buf))
    return out or [("fa", s)]


