FA = "B Lotus"
TITR = "B Titr"
LAT = "Times New Roman"

EN2FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa(s):
    return s.translate(EN2FA)


# ---------------------------------------------------------------- low level
def set_rtl(p):
    pPr = p._p.get_or_add_pPr()
    b = OxmlElement("w:bidi")
    b.set(qn("w:val"), "1")
    pPr.append(b)


def style_run(r, size=12, bold=False, color=None, latin=False, font=None):
    f = font or (LAT if latin else FA)
    r.font.name = f
    r.font.size = Pt(size)
    r.font.bold = bold
    if color:
        r.font.color.rgb = RGBColor(*color)
    rPr = r._r.get_or_add_rPr()
    rf = rPr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        rPr.append(rf)
    rf.set(qn("w:cs"), f)
    rf.set(qn("w:ascii"), f)
    rf.set(qn("w:hAnsi"), f)
    szcs = OxmlElement("w:szCs")
    szcs.set(qn("w:val"), str(int(size * 2)))
    rPr.append(szcs)
    if not latin:
        rtl = OxmlElement("w:rtl")
        rtl.set(qn("w:val"), "1")
        rPr.append(rtl)
    lang = OxmlElement("w:lang")
    lang.set(qn("w:bidi"), "fa-IR")
    rPr.append(lang)


def para(doc, text, size=12, bold=False, align="just", color=None,
         space_before=0, space_after=4, font=None, indent=None):
    p = doc.add_paragraph()
    set_rtl(p)
    p.alignment = {"just": WD_ALIGN_PARAGRAPH.JUSTIFY,
                   "right": WD_ALIGN_PARAGRAPH.RIGHT,
                   "center": WD_ALIGN_PARAGRAPH.CENTER}[align]
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.15
    if indent is not None:
        pf.right_indent = Cm(indent)
    if text:
        r = p.add_run(text)
        style_run(r, size, bold, color, font=font)
    return p


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), hexcolor)
    tcPr.append(sh)


def cell_text(cell, text, size=10.5, bold=False, color=None, align="right", latin=False):
    cell.text = ""
    p = cell.paragraphs[0]
    set_rtl(p)
    p.alignment = {"right": WD_ALIGN_PARAGRAPH.RIGHT,
                   "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "just": WD_ALIGN_PARAGRAPH.JUSTIFY}[align]
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    for i, line in enumerate(text.split("\n")):
        if i:
            p = cell.add_paragraph()
            set_rtl(p)
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
        r = p.add_run(line)
        style_run(r, size, bold, color, latin=latin)


def borders(tbl):
    tblPr = tbl._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement("w:" + edge)
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "6")
        e.set(qn("w:color"), "7F7F7F")
        b.append(e)
    tblPr.append(b)
    bidi = OxmlElement("w:bidiVisual")
    tblPr.append(bidi)


def hrule(doc):
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bo = OxmlElement("w:bottom")
    bo.set(qn("w:val"), "single")
    bo.set(qn("w:sz"), "8")
    bo.set(qn("w:color"), "1F3864")
    pbdr.append(bo)
    pPr.append(pbdr)
    p.paragraph_format.space_after = Pt(6)


